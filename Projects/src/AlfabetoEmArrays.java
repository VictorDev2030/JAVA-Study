public class AlfabetoEmArrays {
    public static void main(String[] args) {
        char[] letters = {'a', 'b', 'c', 'd', 'e', 'f', 'g', 'h',
                            'i', 'f', 'm', 'n', 'o', 'p', 'q', 'r',
                            's', 't', 'u', 'v', 'h', 'x', 'y', 'z'};

        for (char letter : letters){
            System.out.println("Letra: "+letter);
        }
    }
}
